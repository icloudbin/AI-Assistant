// i18n.js (root directory)
// Shared UI-language strings and helpers, used by options.js, sidepanel.js,
// mic-permission.js, and background.js. Follows the same
// "chrome.storage.local + live chrome.storage.onChanged sync" pattern
// already used for THEME_STORAGE_KEY in options.js/sidepanel.js, so
// switching languages on the Settings page updates the side panel
// immediately without a reload, exactly like switching themes does.
//
// This is a small hand-rolled dictionary (translations[lang][key]) rather
// than chrome.i18n/_locales: chrome.i18n messages are fixed per browser
// locale and cannot be swapped at runtime from an in-page control, which is
// what "select a language in Settings and have the UI update immediately"
// requires.
import { LANGUAGE_STORAGE_KEY } from "./storage-keys.js";

export { LANGUAGE_STORAGE_KEY };

// Order here is also the display order of the <select> on the Settings
// page. Each language's own nativeName is shown for every entry (not just
// the currently active language), so a reader can find their language
// regardless of what the UI is currently set to - the standard convention
// used by most multilingual apps.
export const SUPPORTED_LANGUAGES = [
  { code: "en", nativeName: "English" },
  { code: "zh-CN", nativeName: "简体中文" },
  { code: "zh-TW", nativeName: "繁體中文" },
  { code: "fr", nativeName: "Français" },
  { code: "ja", nativeName: "日本語" },
  { code: "es", nativeName: "Español" },
];

const DEFAULT_LANGUAGE = "en";

export function normalizeLanguage(lang) {
  return SUPPORTED_LANGUAGES.some((l) => l.code === lang) ? lang : DEFAULT_LANGUAGE;
}

// Reads the stored language preference (chrome.storage.local). Safe to call
// from the background service worker (no DOM dependency). Defaults to "en"
// when nothing is stored yet or storage is unavailable, matching the
// extension's unmodified/original language.
export async function getStoredLanguage() {
  try {
    const stored = await chrome.storage.local.get(LANGUAGE_STORAGE_KEY);
    return normalizeLanguage(stored[LANGUAGE_STORAGE_KEY]);
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

