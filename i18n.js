// Returns the translated string for `key` in `lang`, substituting any
// {placeholder} tokens found in `vars`. Falls back to English, then to the
// bare key, so a missing language/key never leaves the UI blank.
export function t(lang, key, vars) {
  const table = translations[lang] || translations[DEFAULT_LANGUAGE];
  let str = table[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.split(`{${k}}`).join(String(vars[k]));
    }
  }
  return str;
}

// Convenience wrapper for the handful of strings with an English-style
// one/other count distinction (backup/restore success messages). Chinese
// and Japanese use the same phrasing for both forms (no grammatical
// plural), so `oneKey`/`otherKey` simply resolve to identical strings
// there; French/Spanish/English genuinely differ.
export function tPlural(lang, count, oneKey, otherKey, vars) {
  return t(lang, count === 1 ? oneKey : otherKey, { count, ...vars });
}

// Applies every data-i18n* attribute found under `root` (defaults to the
// whole document). Call this once on load and again whenever the language
// changes - it is cheap and idempotent.
//   data-i18n              -> element.textContent
//   data-i18n-html          -> element.innerHTML (only used for the one
//                              string that intentionally embeds <strong>)
//   data-i18n-placeholder   -> element.placeholder
//   data-i18n-title         -> element.title
//   data-i18n-aria-label    -> the aria-label attribute
export function applyStaticTranslations(lang, root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(lang, el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(lang, el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(lang, el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(lang, el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(lang, el.dataset.i18nAriaLabel));
  });
  if (root === document && document.documentElement) {
    document.documentElement.lang = lang;
  }
}
